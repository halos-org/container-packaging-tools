"""Compose wrapper script generation for container apps."""

from typing import Any

ROUTING_LABELS_DIR = "/run/halos/routing-labels"


def generate_compose_wrapper(context: dict[str, Any]) -> str:
    """Generate the `compose` wrapper installed beside docker-compose.yml.

    The wrapper runs `docker compose` with the shipped docker-compose.yml, the
    routing-labels file for routed apps, and the admin's compose.d/ fragments,
    passing its arguments through. `check` validates the project with the
    environment the unit gives it.

    Args:
        context: Template context from build_context, the same one service.j2
            renders from, so the env file paths cannot drift from the unit's.

    Returns:
        POSIX sh script content as string
    """
    service = context["service"]
    package_name = context["package"]["name"]
    app_id = context["package"]["app_id"]
    has_routing = context["has_routing"]

    env_files = [
        service["env_defaults_file"],
        service["env_file"],
        service["runtime_env_file"],
    ]
    if has_routing:
        env_files.append(service["domain_env_file"])

    lines = [
        "#!/bin/sh",
        f"# Compose wrapper for {package_name}",
        "# Auto-generated by container-packaging-tools",
        "set -e",
        'cd "$(dirname "$0")"',
        "# Fragments apply in byte order, whatever the caller's locale.",
        "LC_ALL=C",
        "",
        'if [ "${1-}" = check ]; then',
        "    # Validate with the environment the unit gives compose.",
        "    set -a",
    ]
    lines.extend(f'    if [ -f "{f}" ]; then . "{f}"; fi' for f in env_files)
    lines.extend(
        [
            "    set +a",
            "    export HALOS_SYSTEMD_STARTED=1",
            "    set -- config --quiet",
            "fi",
            "",
            "# Append the -f list after the caller's arguments, then rotate those",
            "# arguments to the end; set -- keeps names with spaces whole.",
            "nargs=$#",
            # -p wins over a fragment's top-level name:, which would otherwise
            # move `up` off the project ExecStop tears down.
            f'set -- "$@" -p {service["compose_project"]} -f docker-compose.yml',
        ]
    )
    if has_routing:
        labels = f"{ROUTING_LABELS_DIR}/{app_id}.yml"
        lines.append(f'if [ -f "{labels}" ]; then set -- "$@" -f "{labels}"; fi')
    lines.extend(
        [
            'fragments=""',
            "for f in compose.d/*; do",
            '    case "$f" in',
            "        *.yml | *.yaml) ;;",
            "        *) continue ;;",
            "    esac",
            '    [ -f "$f" ] || continue',
            '    set -- "$@" -f "$f"',
            '    fragments="$fragments ${f#compose.d/}"',
            "done",
            'if [ -n "$fragments" ]; then',
            '    echo "compose.d fragments:$fragments" >&2',
            "fi",
            'while [ "$nargs" -gt 0 ]; do',
            '    set -- "$@" "$1"',
            "    shift",
            "    nargs=$((nargs - 1))",
            "done",
            "",
            'exec docker compose "$@"',
            "",
        ]
    )

    return "\n".join(lines)
